source('R/frontends/team/project_library.R')
root<-tempfile();dir.create(root);Sys.setenv(LIPIDOMIC_UPLOAD_QUEUE=root)
u<-'30000000-0000-4000-8000-000000000001';other<-'30000000-0000-4000-8000-000000000002'
p<-tempfile();writeBin(charToRaw('durable test bytes'),p)
x<-team_library_queue(u,list(path=p,project='10000000-0000-4000-8000-000000000001',label='Test'))
unlink(p)
stopifnot(file.exists(x$path),is.null(team_library_queue(other)),identical(team_library_queue(u)$sha256,x$sha256))
# A fresh R process reads the same identity-scoped pending bytes after the session is gone.
script<-tempfile(fileext='.R');writeLines(c("source('R/frontends/team/project_library.R')",sprintf("stopifnot(!is.null(team_library_queue('%s')))",u)),script)
stopifnot(system2(file.path(R.home('bin'),'Rscript'),c('--vanilla',script))==0)
expect_error<-function(expr)stopifnot(inherits(tryCatch({force(expr);NULL},error=identity),'error'))
expect_error(team_library_queue(u,list(path=x$path,project=x$project,label='Other')))
