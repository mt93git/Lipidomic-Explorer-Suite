stopifnot(file.exists(x$path))
writeBin(charToRaw('changed'),x$path);expect_error(team_library_queue(u))
team_library_queue(u,clear=TRUE,expected=x$sha256)
stopifnot(is.null(team_library_queue(u)))
unlink(root,recursive=TRUE);unlink(script)
