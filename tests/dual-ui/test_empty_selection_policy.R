source('R/utils_preparation.R')
d <- data.frame(Lipid_Name=c('a','b'), A=c(1,2), B=c(3,4))
info <- list(data=d,file_cols=list(c('A','B')))
classic <- preparation_request(info,character(),policy='classic')
team <- preparation_request(info,character(),policy='team')
stopifnot(identical(classic$spec$selected,c('A','B')),length(team$spec$selected)==0L)
stopifnot(identical(preparation_request_preview(classic)$samples,c('A','B')))
stopifnot(inherits(try(preparation_request_preview(team),silent=TRUE),'try-error'))
# Resolving an empty input happens BEFORE QC; never reinterpret an empty QC result.
removed <- preparation_request(info,character(),settings=list(outlierTreatments=list(A='remove',B='remove')),policy='classic')
stopifnot(inherits(try(preparation_request_preview(removed),silent=TRUE),'try-error'))
partial <- preparation_request(info,character(),settings=list(outlierTreatments=list(A='remove')),policy='classic')
stopifnot(identical(preparation_request_preview(partial)$samples,'B'))
stopifnot(inherits(try(preparation_request(info,'unknown',policy='classic'),silent=TRUE),'try-error'))
cat('PASS: Classic empty-widget fallback, Team explicit-none, and post-QC no-reinclusion\n')
