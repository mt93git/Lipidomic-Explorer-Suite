# Generate private real-data payloads for the isolated transport fixture.
# PRIVATE_HUB_RDS and PRIVATE_PAYLOAD_DIR must point outside public evidence.
library(shiny);library(plotly)
`%||%`<-function(x,y)if(is.null(x))y else x
source('R/utils_plot_events.R');source('R/sample_metadata_import.R');source('R/results_dashboard.R')
hubs<-readRDS(Sys.getenv('PRIVATE_HUB_RDS'));d<-hubs$team;value<-function(x){force(x);function(...)x}
h<-list(data_processed=value(d$matrix),all_metadata=value(d$metadata),preparation_audit=value(list(normalization='median',imputation='QRILC')),preparation_dirty=value(FALSE),color_maps=value(hubs$classic$color_maps),class_color_map=value(hubs$classic$class_colors))
server<-function(input,output,session)results_dashboard_module_server(input,output,session,h)
payload_dir<-Sys.getenv('PRIVATE_PAYLOAD_DIR');stopifnot(nzchar(payload_dir),ncol(d$matrix)==68L);dir.create(payload_dir,showWarnings=FALSE,recursive=TRUE)
testServer(server,{
 session$setInputs(color_by='Group1',violin_lipid=d$matrix$Lipid_Name[1],pca_transform='log2',pca_scale='uv',n_class=7,top_n=50);session$flushReact()
 for(id in c('pca','violin','dist','comp','heat'))writeLines(output[[paste0('plot_',id)]],file.path(payload_dir,paste0(id,'.json')))
})
# Preserve production UI markup privately, including genuine card/control wrappers.
writeLines(as.character(results_dashboard_ui()),file.path(payload_dir,'dashboard-ui.html'))
source('R/guided_workflow.R');source('R/cell_show.R')
writeLines(as.character(cell_show_ui()),file.path(payload_dir,'cell-ui.html'))
server<-function(input,output,session)cell_show_server(input,output,session,h)
testServer(server,{
 feature<-d$matrix$Lipid_Name[1]
 session$setInputs(cell_group_column='Group1',cell_reference_group='Healthy',cell_comparison_group='SC-SteadyState',cell_class=rd_class(feature),cell_lipid=feature,cell_sample=names(d$matrix)[2],cell_explore_level='feature',cell_profile_view='share');session$flushReact()
 for(id in c('cell_lipid_plot','cell_profile_plot','cell_class_plot','cell_comparison_plot'))writeLines(output[[id]],file.path(payload_dir,paste0(id,'.json')))
 # Dynamic class plot markup is generated by the real renderUI callback.
 writeLines(output$cell_class_plot_ui$html,file.path(payload_dir,'cell-class-ui.html'))
})
