server <- function(input,output,session) {
  bridge <- reactiveVal(NULL)
  hub <- shared_data_server('hub',external_settings=bridge,preparation_policy='team',design_check=function() TRUE,root_session=session)
  qc <- qc_boxplot_server('qc',hub,reactive(list()))
  observe({req(qc());bridge(qc())})
}
