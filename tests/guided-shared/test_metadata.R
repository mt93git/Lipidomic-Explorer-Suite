source('R/utils_sample_metadata.R')
source('R/utils_session_archive.R')
checks <- character()
check <- function(label,value){stopifnot(isTRUE(value));checks <<- c(checks,label)}
reject <- function(expr)inherits(tryCatch(force(expr),error=identity),'error')
x <- data.frame(SampleID=c('S02','S01','S03','S04','unused'),Condition=c('Control','Control','Treatment','Treatment','Other'),SubjectID=c('P2','P1','P1','P2','P9'),TimePoint=c('6hr','Visit 1','24hr','Visit 1','unused'),Batch='B1',stringsAsFactors=FALSE)
ids <- c('S01','S02','S03','S04')
s <- stage_metadata_v01(x,ids,c(Group1='Condition',PatientNumber='SubjectID',TimePoint='TimePoint'))
check('Extra master rows are warned and excluded',s$validation$valid && nrow(s$validation$data)==4 && any(grepl('extra metadata',s$validation$warnings)))
check('Exact matrix order preserved',identical(s$validation$data$SampleID,ids))
check('Confirmation required',reject(confirm_metadata_v01(s)))
m <- confirm_metadata_v01(s,TRUE)
check('Safe optional hub columns',all(m$scientific_metadata$Group2=='All') && all(c('PatientNumber','TimePoint','Replicate')%in%names(m$scientific_metadata)))
check('Alphanumeric timepoints preserved',identical(m$scientific_metadata$TimePoint,c('Visit 1','6hr','24hr','Visit 1')))
check('Batch remains descriptive',! 'Batch'%in%names(m$scientific_metadata) && 'Batch'%in%names(m$display_metadata))
y<-x;y$Condition[3]<-'Stimulated';v<-validate_sample_metadata_v01(y,ids,paired=TRUE)
check('Incomplete multi-condition longitudinal studies load with warning',v$valid && any(grepl('Multiple conditions',v$warnings)) && any(grepl('Incomplete',v$warnings)))
check('Missing matrix ID rejected',!validate_sample_metadata_v01(x[-1,],ids)$valid)
y<-x;y$SampleID[2]<-'S02';check('Duplicate IDs rejected',!validate_sample_metadata_v01(y,ids)$valid)
y<-x;y$SampleID[2]<-' S01';check('Whitespace does not silently remap IDs',!validate_sample_metadata_v01(y,ids)$valid)
y<-x;y$Condition[2]<-'literal SHIELD biological label';m<-confirm_metadata_v01(stage_metadata_v01(y,ids,c(Group1='Condition')),TRUE)
check('Direct mapping bypasses SHIELD token rewriting',m$scientific_metadata$Group1[1]=='literal SHIELD biological label')
y<-x;y$TimeValue<-c('6','1','24','1','0');y$TimeUnit<-c('h','d','h','d','h')
check('Mixed numeric time units rejected for scientific mapping',reject(stage_metadata_v01(y,ids,c(TimePoint='TimeValue'))))
check('Same column cannot be mapped to two scientific fields',reject(stage_metadata_v01(x,ids,c(Group1='Condition',Group2='Condition'))))
y<-x;y$SampleType<-'Pooled QC';y$TimeValue<-'baseline'
v<-stage_metadata_v01(y,ids,c(Group1='Condition'))
check('Descriptive sample type and time labels cannot reject ingestion',v$validation$valid && length(v$validation$warnings)>=2)
check('Descriptive time still requires conversion before scientific mapping',reject(stage_metadata_v01(y,ids,c(TimePoint='TimeValue'))))
# Real ZIP packaging and reading, including legacy state without a sidecar.
d<-tempfile();dir.create(d);dir.create(file.path(d,'data_files'));write.csv(data.frame(Lipid_Name='PC(34:1)',S01=1),file.path(d,'data_files','raw.csv'),row.names=FALSE)
state<-list(inputs=list(selectedColumns='S01'),uploads=list(raw='data_files/raw.csv'))
jsonlite::write_json(state,file.path(d,'state.json'),auto_unbox=TRUE)
z<-tempfile(fileext='.zip');zip::zipr(z,c('state.json','data_files'),root=d)
a<-read_session_archive(z);check('Legacy ZIP remains readable',is.null(a$shared)&&file.exists(file.path(a$directory,'data_files','raw.csv')))
unlink(a$directory,recursive=TRUE)
jsonlite::write_json(list(version='1',metadata=metadata_sidecar_encode(confirm_metadata_v01(s,TRUE))),file.path(d,'shared-state-v1.json'),auto_unbox=TRUE,dataframe='rows')
zip::zipr(z,c('state.json','data_files','shared-state-v1.json'),root=d)
a<-read_session_archive(z);check('Versioned metadata survives a real ZIP',identical(a$shared$metadata$display_metadata$SampleID,ids))
check('Target mapping names survive JSON and restore',identical(a$shared$metadata$mappings,s$mappings))
unlink(a$directory,recursive=TRUE)
state$uploads$raw <- '../outside.csv';jsonlite::write_json(state,file.path(d,'state.json'),auto_unbox=TRUE);zip::zipr(z,'state.json',root=d)
check('ZIP state cannot reference outside files',reject(read_session_archive(z)))
check('ZIP extraction size limit enforced',reject(read_session_archive(z,max_bytes=1)))
unlink(c(d,z),recursive=TRUE)
# External attributes are not safely represented by zip_list$permissions.
# Exercise actual link/traversal ZIP entries, not merely suspicious state paths.
unsafe<-tempfile();dir.create(unsafe)
python<-Sys.which('python3');stopifnot(nzchar(python))
stopifnot(system2(python,c('tests/guided-shared/make_archive_fixtures.py',shQuote(unsafe)))==0)
for(case in c('traversal','absolute','alias','symlink-chain'))
  check(paste('Unsafe archive entry rejected:',case),reject(suppressWarnings(read_session_archive(file.path(unsafe,paste0(case,'.zip'))))))
a<-read_session_archive(file.path(unsafe,'symlink.zip'))
p<-file.path(a$directory,'data_files/raw.csv')
check('Symlink attributes never create a filesystem link',identical(Sys.readlink(p),'') || is.na(Sys.readlink(p)))
check('Symlink target is not dereferenced',identical(readLines(p,warn=FALSE),gsub('/+','/',file.path(unsafe,'outside-sentinel.txt'))))
check('Link chain cannot create a file outside extraction',!file.exists(file.path(unsafe,'escape.csv')))
unlink(c(unsafe,a$directory),recursive=TRUE)
args<-commandArgs(TRUE);if(length(args))write.csv(data.frame(check=checks,status='PASS'),file.path(args[1],'metadata-and-archive.csv'),row.names=FALSE)
cat(sprintf('PASS: %d metadata and archive checks\n',length(checks)))
