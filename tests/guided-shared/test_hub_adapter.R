source('R/global.R')
checks<-character();check<-function(n,x){stopifnot(isTRUE(x));checks<<-c(checks,n)}
settings<-shiny::reactiveVal(list(useImputation=FALSE,normalizationMethod='none',imputeZerosPerFile=TRUE,imputeRemainingNAtoZero=TRUE,minDetectionPct=0,dropNonDetected=FALSE,detectionScope='global',outlierTreatments=list(),outlier_trigger=0))
approved<-shiny::reactiveVal(FALSE)
f<-normalizePath('tests/guided-shared/fixtures/abundance.csv');md<-read_sample_metadata_v01('tests/guided-shared/fixtures/metadata.csv')
fixture<-read.csv(f,check.names=FALSE)
shiny::testServer(shared_data_server,args=list(external_settings=shiny::reactive(settings()),design_check=function()approved()),{
  session$flushReact()
  session$setInputs(files=data.frame(name='adapter-fixture.csv',size=file.info(f)$size,type='text/csv',datapath=f),selectedColumns=names(fixture)[-1])
  session$setInputs(runAnalysis=1);session$flushReact()
  check('Unconfirmed guided design cannot prepare',is.null(data_processed_full()))
  stage<-stage_metadata_v01(md,names(fixture)[-1],c(Group1='Condition',Group2='Tissue',PatientNumber='SubjectID',Replicate='ReplicateID',TimePoint='TimePoint'))
  api<-session$returned
  check('Direct adapter rejects absent confirmation',inherits(tryCatch(api$set_external_sample_metadata(stage),error=identity),'error'))
  api$set_external_sample_metadata(stage,TRUE);session$flushReact()
  check('Uploaded groups bypass filename parser',identical(allParsedMetadata()$Group1,md$Condition))
  check('Descriptive batch is not a scientific factor',!'Batch'%in%names(allParsedMetadata()))
  session$setInputs(ensure_analysis_run=1);session$flushReact()
  check('Navigation does not implicitly execute guided preparation',is.null(data_processed_full()))
  approved(TRUE);session$setInputs(runAnalysis=2);session$flushReact()
  before<-data_processed_full()
  check('Explicit run uses the production hub',nrow(before)==12 && ncol(before)==9)
  check('No-imputation no-normalization agrees with input',isTRUE(all.equal(before,fixture,tolerance=1e-12)))
  archive_path<-output$export_session_btn
  archive<-read_session_archive(archive_path)
  check('Actual session handler writes named mappings',identical(archive$shared$metadata$mappings,stage$mappings))
  check('Applied selection and settings survive JSON',identical(archive$shared$applied$spec$selected,names(fixture)[-1]) && identical(archive$shared$applied$spec$settings$normalizationMethod,'none'))
  restored<-metadata_sidecar_decode(metadata_sidecar_encode(archive$shared$metadata))
  check('Restored metadata produces identical hub table',identical(restored$scientific_metadata,allParsedMetadata()))
  unlink(archive$directory,recursive=TRUE)
  nextmd<-md;nextmd$Condition<-rev(md$Condition)
  approved(FALSE)
  api$set_external_sample_metadata(stage_metadata_v01(nextmd,names(fixture)[-1],stage$mappings),TRUE);session$flushReact()
  check('New metadata withholds old numerical outputs',is.null(data_processed_full()))
  session$setInputs(runAnalysis=3);session$flushReact()
  check('Revoked approval blocks a new run',preparation$state()$revision==1)
  approved(TRUE);session$setInputs(runAnalysis=4);session$flushReact()
  check('Confirmed metadata re-run recovers',preparation$state()$status=='ready')
  session$setInputs(unselectAll=1,selectedColumns=character());session$flushReact()
  session$setInputs(runAnalysis=5);session$flushReact()
  check('Intentional deselection cannot silently reinclude samples',is.null(data_processed_full()))
  unlink(unlist(rv$uploads))
})
# Classic defaults must handle features without signal without a reactive crash.
sparse<-rbind(fixture, c('PC(90:0)',rep(0,8)), c('PC(92:0)',rep(NA,8)))
for(k in names(sparse)[-1])sparse[[k]]<-as.numeric(sparse[[k]])
sparse_file<-tempfile(fileext='.csv');write.csv(sparse,sparse_file,row.names=FALSE,na='')
shiny::testServer(shared_data_server,{
  session$setInputs(files=data.frame(name='sparse-fixture.csv',size=file.info(sparse_file)$size,type='text/csv',datapath=sparse_file),selectedColumns=names(sparse)[-1])
  session$setInputs(runAnalysis=1);session$flushReact()
  z<-data_processed_full()
  check('Classic default QRILC tolerates all-zero and all-NA rows',!is.null(z)&&nrow(z)==14&&!anyNA(z))
  check('Classic default zero detection filtering preserves absent features',all(c('PC(90:0)','PC(92:0)')%in%z$Lipid_Name))
  unlink(unlist(rv$uploads))
})
unlink(sparse_file)
args<-commandArgs(TRUE);if(length(args))write.csv(data.frame(check=checks,status='PASS'),file.path(args[1],'guided-hub-adapter.csv'),row.names=FALSE)
cat(sprintf('PASS: %d guided hub adapter checks\n',length(checks)))
